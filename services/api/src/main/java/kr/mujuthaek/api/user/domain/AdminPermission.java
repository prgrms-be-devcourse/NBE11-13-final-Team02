package kr.mujuthaek.api.user.domain;

/**
 * 일반 관리자에게 하나씩 주는 관리 권한. 한 권한이 그 화면의 보기와 처리를 함께 해요. 최상위 관리자는 모두 가진 것으로 봐요.
 *
 * <p>주고 빼는 규칙은 {@code AdminUserService}: 「권한 부여」가 있어야 하고, 내가 가진 권한만 주고 뺄 수 있어요. 「권한 부여」 자체를 주고 빼는
 * 일과 「권한 부여」를 가진 관리자를 바꾸는 일은 최상위만 해요.
 */
public enum AdminPermission {
  /** 공고 검수: 공고 추출 결과 승인·반려·수정·다시 열기 */
  NOTICE_REVIEW,
  /** 혜택 검수: 혜택 정책 승인·반려·수정·다시 열기 */
  BENEFIT_REVIEW,
  /** 수집 출처: 출처 일시 중지·재개·즉시 수집 */
  SOURCES,
  /** 판정 기준: 중위소득·도시근로자 소득·순위 기준값 수정, 규제지역 지정·종료 */
  CRITERIA,
  /** 제보 처리: 공고·혜택·창업 사업 제보, 생활권 제보 */
  REPORTS,
  /** 채팅 제재: 채팅 신고 메시지 계속 가리기·되돌리기 */
  CHAT,
  /** 회원 보기: 회원 목록·찾기 */
  USERS_VIEW,
  /** 이용 정지: 회원 이용 정지·해제 */
  USERS_SUSPEND,
  /** 관리자 지정: 일반 회원을 일반 관리자로 지정·해제 */
  ADMIN_APPOINT,
  /** 권한 부여: 내가 가진 권한을 다른 관리자에게 주고 빼기 */
  PERMISSION_GRANT,
  /** 트래픽 보기: GA·서버 방문 통계, 봇 */
  TRAFFIC,
  /** 처리 기록 보기: 모든 관리자의 처리 기록 */
  ACTIVITY
}
