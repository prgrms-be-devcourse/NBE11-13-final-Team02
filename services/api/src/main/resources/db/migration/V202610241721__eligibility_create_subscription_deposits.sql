-- 민영주택 1순위 기준이지만 공공주택에도 쓰여요:
--   전용 85㎡ 초과 공공건설임대주택 (주택공급에 관한 규칙 제28조제1항제1호 단서)
--   전용 85㎡ 초과 장기전세주택 (공공주택 특별법 시행규칙 제18조제1항제2호 → 주택공급에 관한 규칙 제4장)
-- 지역(region)은 입주자모집공고일 현재 신청자의 주민등록 거주지예요 (별표 2 비고)
--   SEOUL_BUSAN = 특별시 및 부산광역시, METROPOLITAN = 그 밖의 광역시, OTHER = 특별시 및 광역시를 제외한 지역
-- max_area_m2는 "공급받을 수 있는 주택의 전용면적" 상한이에요 (null = 모든 면적)
-- 표가 바뀌면 코드는 그대로 두고 effective_from(시행일)이 다른 행 12개를 새 마이그레이션으로 더해요. 판정은 기준일 이전의 가장 늦은 표를 써요
create table eligibility.subscription_deposits (
    id             uuid         primary key,
    effective_from date         not null,
    region         text         not null check (region in ('SEOUL_BUSAN', 'METROPOLITAN', 'OTHER')),
    max_area_m2    numeric(6,2) check (max_area_m2 > 0),
    amount_won     bigint       not null check (amount_won > 0),
    source         text         not null,
    unique nulls not distinct (effective_from, region, max_area_m2)
);

